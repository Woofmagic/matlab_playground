x_data = rand(100, 1);
y_data = rand(100, 1);

scatter_object = scatter( ...
    x_data, ...
    y_data, ...
    "Marker", 'o', ...
    "LineWidth", 0.01, ...
    "MarkerEdgeColor", 'black', ...
    "MarkerFaceColor", 'black', ...
    "MarkerEdgeAlpha", 1.0, ...
    "MarkerFaceAlpha", 1.0, ...
    "AlphaData", 1, ...
    "AlphaDataMode", 'auto', ...
    "AlphaDataMapping", "scaled", ...
    "XData", x_data);

% x-tick angles relative to horizontal:
xtickangle(45)

% y-tick angles relative to horizontal:
ytickangle(90)

